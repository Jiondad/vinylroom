// Apply private manual settings to a fresh public bundle AFTER production build.
// Source photographs stay in public-assets. Hidden assets are not copied to out.
import {readFile,writeFile,mkdir,copyFile,rm} from 'node:fs/promises';
import {resolve,sep} from 'node:path';
import {createHash} from 'node:crypto';
await readFile('out/index.html');
const source=JSON.parse(await readFile('public-assets/artist-profiles/profiles.json','utf8'));
const overrides=JSON.parse(await readFile('config/artist-manual-overrides.json','utf8'));
if(source.schema!==1||overrides.schema!==1||!overrides.artists)throw Error('invalid_artist_manifest');
const profiles=structuredClone(source.profiles);
for(const [key,entry] of Object.entries(overrides.artists)){
 if(!entry.name||typeof entry.hidden!=='boolean')throw Error('invalid_manual_override:'+key);
 // APPROVED variants must be generated by the NAS exporter, never guessed here.
 if(entry.manual){
  const token=createHash('sha256').update('manual:'+key+':'+entry.manual.source_sha256).digest('hex').slice(0,24);
  const p=profiles[entry.name];
  if(!p||p.thumb!=='images/'+token+'-thumb.webp'||p.full!=='images/'+token+'-full.webp')throw Error('matching_NAS_manual_export_required');
 }else if(entry.hidden)delete profiles[entry.name];
}
const root=resolve('public-assets/artist-profiles');
const dest='out/artist-profiles';
await rm(dest,{recursive:true,force:true});await mkdir(dest+'/images',{recursive:true});
const copied=new Set();
for(const entry of Object.values(profiles))for(const kind of ['thumb','full']){
 const rel=entry[kind];
 if(!/^images\/[a-f0-9]{24}-(thumb|full)\.webp$/.test(rel)||!rel.endsWith('-'+kind+'.webp'))throw Error('invalid_artist_asset');
 const src=resolve(root,rel);if(!src.startsWith(root+sep))throw Error('invalid_asset_root');
 if(!copied.has(rel)){await copyFile(src,dest+'/'+rel);copied.add(rel);}
}
await writeFile(dest+'/profiles.json',JSON.stringify({schema:1,profiles},null,2)+'\n');
console.log('Public Artist bundle: '+Object.keys(profiles).length+' profiles; hidden variants excluded; source originals preserved');
